Base.transpose(K::AbstractKLUFactorization) = TransposeFactorization(K)

# Assigning a new symbolic/numeric pointer releases the one it replaces, so that
# re-running `klu_factor!` on an already factored object does not leak the old factor.
# Numeric factors belong to their symbolic analysis, so they are released with it.
function setproperty!(klu::AbstractKLUFactorization, s::Symbol, x)
    new = convert(fieldtype(typeof(klu), s), x)
    if s === :_symbolic && new != getfield(klu, s)
        _free_numeric(klu)
        _free_symbolic(klu)
    elseif s === :_numeric && new != getfield(klu, s)
        _free_numeric(klu)
    end
    return setfield!(klu, s, new)
end

# Certain sets of inputs must be non-null *together*:
# [Lp, Li, Lx], [Up, Ui, Ux], [Fp, Fi, Fx]
for Tv ∈ KLUValueTypes, Ti ∈ KLUIndexTypes
    extract = _klu_name("extract", Tv, Ti)
    sort = _klu_name("sort", Tv, Ti)
    if Tv === :ComplexF64
        call = :($extract(klu._numeric, klu._symbolic, Lp, Li, Lx, Lz, Up, Ui, Ux, Uz, Fp, Fi, Fx, Fz, P, Q, Rs, R, Ref(klu.common)))
    else
        call = :($extract(klu._numeric, klu._symbolic, Lp, Li, Lx, Up, Ui, Ux, Fp, Fi, Fx, P, Q, Rs, R, Ref(klu.common)))
    end
    @eval begin
        function _extract!(
            klu::AbstractKLUFactorization{$Tv, $Ti};
            Lp = C_NULL, Li = C_NULL, Up = C_NULL, Ui = C_NULL, Fp = C_NULL, Fi = C_NULL,
            P = C_NULL, Q = C_NULL, R = C_NULL, Lx = C_NULL, Lz = C_NULL, Ux = C_NULL, Uz = C_NULL,
            Fx = C_NULL, Fz = C_NULL, Rs = C_NULL
        )
            Base.@lock klu begin
                klu._numeric == C_NULL && throw(ArgumentError("This KLUFactorization has not yet been factored. Try `klu_factor!`."))
                status = klu.common.status
                $sort(klu._symbolic, klu._numeric, Ref(klu.common)) == 1 || kluerror(klu.common)
                ok = $call
                if ok == 1
                    klu.common.status = status # libklu resets it, which would hide KLU_SINGULAR
                    return nothing
                else
                    kluerror(klu.common)
                end
            end
        end
    end
end

function Base.propertynames(::AbstractKLUFactorization, private::Bool=false)
    publicnames = (:lnz, :unz, :nzoff, :L, :U, :F, :q, :p, :Rs,)
    # `symbolic` and `numeric` are copies of libklu's structs, with pointers into its memory.
    privatenames = (:symbolic, :numeric, :nblocks, :maxblock, :lock, :(_L), :(_U), :(_F))
    if private
        return (publicnames..., privatenames...)
    else
        return publicnames
    end
end

function getproperty(klu::AbstractKLUFactorization{Tv, Ti}, s::Symbol) where {Tv<:KLUTypes, Ti<:KLUITypes}
    # Forwards to the numeric struct:
    if s ∈ (:lnz, :unz, :nzoff)
        return getproperty(klu.numeric, s)
    end
    if s ∈ (:nblocks, :maxblock)
        return getproperty(klu.symbolic, s)
    end
    # libklu has no getters, so these copy its structs. They are the only reads of libklu's memory.
    if s === :symbolic
        Base.@lock klu begin
            klu._symbolic == C_NULL && throw(ArgumentError("This KLUFactorization has not yet been analyzed. Try `klu_analyze!`."))
            if Ti == Int64
                return unsafe_load(Ptr{klu_l_symbolic}(klu._symbolic))
            else
                return unsafe_load(Ptr{klu_symbolic}(klu._symbolic))
            end
        end
    end
    if s === :numeric
        Base.@lock klu begin
            klu._numeric == C_NULL && throw(ArgumentError("This KLUFactorization has not yet been factored. Try `klu_factor!`."))
            if Ti == Int64
                return unsafe_load(Ptr{klu_l_numeric}(klu._numeric))
            else
                return unsafe_load(Ptr{klu_numeric}(klu._numeric))
            end
        end
    end
    # Non-overloaded parts:
    if s ∉ (:L, :U, :F, :p, :q, :R, :Rs, :(_L), :(_U), :(_F))
        return getfield(klu, s)
    end
    # Factor parts:
    # The lock is held from sizing the buffers to filling them, as refactoring from another task
    # could otherwise change the sizes, and libklu would write past the end of the buffers.
    if s ∈ (:(_L), :(_U), :(_F), :q, :p, :R, :Rs)
        Base.@lock klu begin
            if s === :(_L)
                lnz = klu.lnz
                Lp = Vector{Ti}(undef, klu.n + 1)
                Li = Vector{Ti}(undef, lnz)
                Lx = Vector{Float64}(undef, lnz)
                # could also be replaced with multiple dispatch.
                Lz = Tv == Float64 ? C_NULL : Vector{Float64}(undef, lnz)
                _extract!(klu; Lp, Li, Lx, Lz)
                return Lp, Li, Lx, Lz
            elseif s === :(_U)
                unz = klu.unz
                Up = Vector{Ti}(undef, klu.n + 1)
                Ui = Vector{Ti}(undef, unz)
                Ux = Vector{Float64}(undef, unz)
                Uz = Tv == Float64 ? C_NULL : Vector{Float64}(undef, unz)
                _extract!(klu; Up, Ui, Ux, Uz)
                return Up, Ui, Ux, Uz
            elseif s === :(_F)
                fnz = klu.nzoff
                # We often don't have an F, so create the right vectors for an empty SparseMatrixCSC
                if fnz == 0
                    Fp = zeros(Ti, klu.n + 1)
                    Fi = Vector{Ti}()
                    Fx = Vector{Float64}()
                    Fz = Tv == Float64 ? C_NULL : Vector{Float64}()
                else
                    Fp = Vector{Ti}(undef, klu.n + 1)
                    Fi = Vector{Ti}(undef, fnz)
                    Fx = Vector{Float64}(undef, fnz)
                    Fz = Tv == Float64 ? C_NULL : Vector{Float64}(undef, fnz)
                    _extract!(klu; Fp, Fi, Fx, Fz)
                    # F is *not* sorted on output, so we'll have to do it here:
                    for i ∈ 1:(length(Fp) - 1)
                        # find each segment
                        first = Fp[i] + 1
                        last = Fp[i+1]
                        first > last && (continue)
                        first == length(Fi) && (break)
                        # sort each column of rowval, nzval, and Fz for complex numbers if necessary
                        #by the ascending permutation of rowval.
                        Fiview = view(Fi, first:last)
                        Fxview = view(Fx, first:last)
                        P = sortperm(Fiview)
                        Fiview .= Fiview[P]
                        Fxview .= Fxview[P]
                        if Fz != C_NULL && length(Fz) == length(Fx)
                            Fzview = view(Fz, first:last)
                            Fzview .= Fzview[P]
                        end
                    end
                end
                return Fp, Fi, Fx, Fz
            end
            if s ∈ (:q, :p, :R, :Rs)
                if s === :Rs
                    out = Vector{Float64}(undef, klu.n)
                elseif s === :R
                    out = Vector{Ti}(undef, klu.nblocks + 1)
                else
                    out = Vector{Ti}(undef, klu.n)
                end
                # This tuple construction feels hacky, there's a better way I'm sure.
                s === :q && (s = :Q)
                s === :p && (s = :P)
                _extract!(klu; NamedTuple{(s,)}((out,))...)
                if s ∈ (:Q, :P, :R)
                    increment!(out)
                end
                return out
            end
        end
    end
    if s ∈ (:L, :U, :F)
        if s === :L
            p, i, x, z = klu._L
        elseif s === :U
            p, i, x, z = klu._U
        elseif s === :F
            p, i, x, z = klu._F
        end
        if Tv == Float64
            return SparseMatrixCSC(klu.n, klu.n, increment!(p), increment!(i), x)
        else
            return SparseMatrixCSC(klu.n, klu.n, increment!(p), increment!(i), Complex.(x, z))
        end
    end
end

function LinearAlgebra.issuccess(K::AbstractKLUFactorization; allowsingular=false)
    return Base.@lock K (allowsingular ? K.common.status >= KLU_OK : K.common.status == KLU_OK) && K._numeric != C_NULL
end
function show(io::IO, mime::MIME{Symbol("text/plain")}, K::AbstractKLUFactorization)
    summary(io, K); println(io)
    # Extract all the factors first, so that they are from one factorization, and printing to
    # a slow `io` does not hold up other tasks.
    factors = Base.@lock K K._numeric == C_NULL ? nothing : (K.L, K.U, K.F)
    if factors === nothing
        println(io, "Incomplete Factorization, please try `klu_factor!(K)`.")
    else
        L, U, F = factors
        println(io, "L factor:")
        show(io, mime, L)
        println(io, "\nU factor:")
        show(io, mime, U)
        println(io, "\nF factor:")
        show(io, mime, F)
    end
end

"""
    klu_analyze!(K::KLUFactorization; check = true)

Compute and store (as `K._symbolic`) a symbolic factorization of the sparse matrix \
represented by the fields of `K`."""
function klu_analyze!(K::KLUFactorization{Tv, Ti}; check=true) where {Tv, Ti<:KLUITypes}
    Base.@lock K begin
        if K._symbolic != C_NULL return K end
        _check_lengths(K)
        if Ti == Int64
            sym = klu_l_analyze(K.n, K.colptr, K.rowval, Ref(K.common))
        else
            sym = klu_analyze(K.n, K.colptr, K.rowval, Ref(K.common))
        end
        if sym == C_NULL && check
            kluerror(K.common)
        else
            K._symbolic = sym
            K._perms = nothing
        end
    end
    return K
end

"""
    klu_analyze!(K::KLUFactorization{Tv, Ti}, P::Vector{Ti}, Q::Vector{Ti}; check = true)

Variant of `klu_analyze!` that allows for user-provided permutation vectors `P` and `Q`,
which are zero-based, unlike `K.p` and `K.q`. Like `klu_analyze!`, this does nothing if `K`
has already been analyzed."""
function klu_analyze!(K::KLUFactorization{Tv, Ti}, P::Vector{Ti}, Q::Vector{Ti}; check=true) where {Tv, Ti<:KLUITypes}
    # libklu does not validate these, and reads out of bounds if they are not permutations.
    # Validate copies, as another task could change the originals after the check.
    P, Q = copy(P), copy(Q)
    all(x -> length(x) == K.n && isperm(x .+ one(Ti)), (P, Q)) ||
        throw(ArgumentError("P and Q must be zero-based permutations of length $(K.n)."))
    Base.@lock K begin
        if K._symbolic != C_NULL return K end
        _check_lengths(K)
        if Ti == Int64
            sym = klu_l_analyze_given(K.n, K.colptr, K.rowval, P, Q, Ref(K.common))
        else
            sym = klu_analyze_given(K.n, K.colptr, K.rowval, P, Q, Ref(K.common))
        end
        if sym == C_NULL && check
            kluerror(K.common)
        else
            K._symbolic = sym
            K._perms = (P, Q)
        end
    end
    return K
end

for Tv ∈ KLUValueTypes, Ti ∈ KLUIndexTypes
    factor = _klu_name("factor", Tv, Ti)
    @eval begin
        function klu_factor!(K::KLUFactorization{$Tv, $Ti}; check=true, allowsingular=false)
            Base.@lock K begin
                _check_lengths(K)
                K._symbolic == C_NULL && klu_analyze!(K; check)
                if K._symbolic != C_NULL
                    K.common.halt_if_singular = !allowsingular && check
                    num = $factor(K.colptr, K.rowval, K.nzval, K._symbolic, Ref(K.common))
                    K.common.halt_if_singular = true
                else
                    num = C_NULL
                end
                # Also on failure: the factors of the previous values must not stay in use.
                K._numeric = num
                if num == C_NULL && check
                    kluerror(K.common)
                else
                    if allowsingular
                        K.common.status < KLU_OK && check && kluerror(K.common)
                    else
                        (K.common.status == KLU_OK) || (check && kluerror(K.common))
                    end
                end
            end
            return K
        end
    end
end

for Tv ∈ KLUValueTypes, Ti ∈ KLUIndexTypes
    rgrowth = _klu_name("rgrowth", Tv, Ti)
    rcond = _klu_name("rcond", Tv, Ti)
    condest = _klu_name("condest", Tv, Ti)
    @eval begin
        function rgrowth(K::KLUFactorization{$Tv, $Ti})
            Base.@lock K begin
                K._numeric == C_NULL && klu_factor!(K)
                _check_lengths(K)
                status = K.common.status
                ok = $rgrowth(K.colptr, K.rowval, K.nzval, K._symbolic, K._numeric, Ref(K.common))
                if ok == 0
                    kluerror(K.common)
                else
                    K.common.status = status # libklu resets it, which would hide KLU_SINGULAR
                    return K.common.rgrowth
                end
            end
        end

        function rcond(K::AbstractKLUFactorization{$Tv, $Ti})
            Base.@lock K begin
                K._numeric == C_NULL && klu_factor!(K)
                status = K.common.status
                ok = $rcond(K._symbolic, K._numeric, Ref(K.common))
                if ok == 0
                    kluerror(K.common)
                else
                    K.common.status = status # libklu resets it, which would hide KLU_SINGULAR
                    return K.common.rcond
                end
            end
        end

        function condest(K::KLUFactorization{$Tv, $Ti})
            Base.@lock K begin
                K._numeric == C_NULL && klu_factor!(K)
                _check_lengths(K)
                status = K.common.status
                ok = $condest(K.colptr, K.nzval, K._symbolic, K._numeric, Ref(K.common))
                if ok == 0
                    kluerror(K.common)
                else
                    K.common.status = status # libklu resets it, which would hide KLU_SINGULAR
                    return K.common.condest
                end
            end
        end
    end
end

