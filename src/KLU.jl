# The sign of a permutation, from the number of its cycles of even length.
function _permsign(p::AbstractVector{<:Integer})
    seen = falses(length(p))
    s = 1
    for i in eachindex(p)
        seen[i] && continue
        len = 0
        j = i
        while !seen[j]
            seen[j] = true
            j = Int(p[j])
            len += 1
        end
        iseven(len) && (s = -s)
    end
    return s
end

"""
    logabsdet(K::KLUFactorization) -> (logabsdet, sign)
    det(K::KLUFactorization)

The log of the absolute value of the determinant of the factored matrix, and its sign, which
has unit magnitude, or is 0 for a singular matrix. `det` is computed from these, and `logdet` is
also available. `K` is factored if it has not been yet.
"""
function LinearAlgebra.logabsdet(K::KLUFactorization{Tv}) where {Tv}
    # `R \\ A[p, q] = L * U + F`, where L has a unit diagonal and `L * U + F` is block upper
    # triangular, with `F` strictly above the diagonal blocks.
    d, Rs, p, q = Base.@lock K begin
        K._numeric == C_NULL && klu_factor!(K)
        diag(K.U), K.Rs, K.p, K.q
    end
    s = Tv(_permsign(p) * _permsign(q))
    logdet = sum(log, Rs; init = 0.0)
    for x in d
        s *= sign(x)
        logdet += log(abs(x))
    end
    return logdet, s
end

LinearAlgebra.logabsdet(K::AdjointFactorization{<:Any, <:KLUFactorization}) =
    ((l, s) = logabsdet(parent(K)); (l, conj(s)))
LinearAlgebra.logabsdet(K::TransposeFactorization{<:Any, <:KLUFactorization}) = logabsdet(parent(K))


"""
    klu_factor!(K::KLUFactorization; check=true, allowsingular=false) -> K::KLUFactorization

Factor `K` into components `K.L`, `K.U`, and `K.F`.
This function will perform both the symbolic and numeric steps of factorization on an
existing `KLUFactorization` instance.

# Arguments
  - `K::KLUFactorization`: The matrix factorization object to be factored.
  - `check::Bool`: If `true` (default) check for errors after the factorization. If `false` errors must be checked by the user with `klu.common.status`.
  - `allowsingular::Bool`: If `true` (default `false`) allow the factorization to proceed even if the matrix is singular. Note that this will allow for \
silent divide by zero errors in subsequent `solve!` or `ldiv!` calls if singularity is not checked by the user with `klu.common.status == KLU.KLU_SINGULAR`

The `K.common` struct can be used to modify certain options and parameters, see the \
[KLU documentation](https://github.com/DrTimothyAldenDavis/SuiteSparse/raw/dev/KLU/Doc/KLU_UserGuide.pdf) \
or [`klu_common`](@ref) for more information.
"""
klu_factor!

"""
    klu(A::SparseMatrixCSC) -> K::KLUFactorization
    klu(n, colptr::Vector{Ti}, rowval::Vector{Ti}, nzval::Vector{Tv}) -> K::KLUFactorization

Compute the LU factorization of a sparse matrix `A` using KLU[^ACM907].

For sparse `A` with real or complex element type, the return type of `K` is
`KLUFactorization{Tv, Ti}`, with `Tv` = `Float64` or `ComplexF64`
respectively and `Ti` is an integer type (`Int32` or `Int64`).


The individual components of the factorization `K` can be accessed by indexing:

| Component | Description                                                      |
|:----------|:-----------------------------------------------------------------|
| `L`       | `L` (lower triangular) part of `LU` of the diagonal blocks       |
| `U`       | `U` (upper triangular) part of `LU` of the diagonal blocks       |
| `F`       | `F` (upper triangular) part of `LU + F`, the off-diagonal blocks |
| `p`       | row permutation `Vector`                                         |
| `q`       | column permutation `Vector`                                      |
| `Rs`      | `Vector` of scaling factors                                      |

The relation between `K` and `A` is

`K.L * K.U + K.F ≈ Diagonal(K.Rs) \\ A[K.p, K.q]`

`K` further supports the following functions:

- `\\`, `ldiv!`, and [`solve!`](@ref) to solve linear systems
- [`klu!`](@ref) to refactor with new values
- [`rcond`](@ref), [`condest`](@ref), and [`rgrowth`](@ref) to check the quality of the factorization
- `det`, `logabsdet`, and `logdet`
- `copy` and `deepcopy`

# Arguments
  - `A::SparseMatrixCSC` or `n::Integer`, `colptr::Vector{Ti}`, `rowval::Vector{Ti}`, `nzval::Vector{Tv}`: The sparse matrix or the zero-based sparse matrix components to be factored.
  - `check::Bool`: If `true` (default) check for errors after the factorization. If `false` errors must be checked by the user with `klu.common.status`.
  - `allowsingular::Bool`: If `true` (default `false`) allow the factorization to proceed even if the matrix is singular.\
   Note that this will allow for silent divide by zero errors in subsequent `solve!` or `ldiv!` calls if singularity is not checked by the user with `klu.common.status == KLU.KLU_SINGULAR`
  - `full_factor::Bool`: if `true` (default), perform both numeric and symbolic factorization. If `false`, only perform symbolic factorization. \
  Useful for cases where only the sparse structure of `A` is known at time of construction.

!!! note
    `klu(A::SparseMatrixCSC)` uses the KLU[^ACM907] library that is part of
    SuiteSparse. As this library only supports sparse matrices with `Float64` or
    `ComplexF64` elements, `klu` converts other values to one of these, in a new vector.

!!! warning "`K` shares vectors with the caller"
    To avoid using more memory, `K` does not copy what it is given. `klu(A)` keeps `nonzeros(A)`,
    `klu(n, colptr, rowval, nzval)` keeps all three vectors, and `klu!(K, nzval)` keeps `nzval`,
    unless the values had to be converted. It is the caller's responsibility not to change
    them in a way that breaks `K`:

    - Changing values does not change the current factors, but later calls to
      [`klu_factor!`](@ref), [`condest`](@ref), [`rgrowth`](@ref), and `copy` read the new values.
    - Resizing a vector, for example with `dropzeros!(A)`, makes the operations that read it throw
      an `ArgumentError` if it became too short.
    - `colptr` and `rowval` must not be changed at all while `K` is in use, as libklu relies on
      them matching its analysis. This is not checked.

!!! note "Thread safety"
    A single `KLUFactorization` may be shared between tasks/threads: every libklu call on
    it is serialized by a per-object lock (see [`KLUFactorization`](@ref)). Solves on
    *distinct* factorizations run fully in parallel. To solve many right-hand sides against
    the same matrix, batch them into the columns of one `B` (a single `solve!` call, which
    runs on one thread), or to solve them in parallel, give each task its own `copy(K)`.

[^ACM907]: Davis, Timothy A., & Palamadai Natarajan, E. (2010). Algorithm 907: KLU, A Direct Sparse Solver for Circuit Simulation Problems. ACM Trans. Math. Softw., 37(3). doi:10.1145/1824801.1824814
"""
function klu(n,
    colptr::Vector{Ti},
    rowval::Vector{Ti},
    nzval::Vector{Tv};
    check=true,
    allowsingular=false,
    full_factor=true,
) where {Ti<:KLUITypes, Tv<:AbstractFloat}
    if Tv != Float64
        nzval = convert(Vector{Float64}, nzval)
    end
    K = KLUFactorization(n, colptr, rowval, nzval)
    return full_factor ? klu_factor!(K; check, allowsingular) : klu_analyze!(K; check)
end

function klu(n,
    colptr::Vector{Ti},
    rowval::Vector{Ti},
    nzval::Vector{Tv};
    check=true,
    allowsingular=false,
    full_factor=true,
) where {Ti<:KLUITypes, Tv<:Complex}
    if Tv != ComplexF64
        nzval = convert(Vector{ComplexF64}, nzval)
    end
    K = KLUFactorization(n, colptr, rowval, nzval)
    return full_factor ? klu_factor!(K; check, allowsingular) : klu_analyze!(K; check)
end

function klu(A::SparseMatrixCSC{Tv, Ti};
    check=true,
    allowsingular=false,
    full_factor=true,
) where {Tv<:Union{AbstractFloat, Complex}, Ti<:KLUITypes}
    n = size(A, 1)
    n == size(A, 2) || throw(DimensionMismatch())
    return klu(n,
        decrement(A.colptr),
        decrement(A.rowval),
        A.nzval;
        check,
        allowsingular,
        full_factor
    )
end

"""
    klu!(K::KLUFactorization, A::SparseMatrixCSC; check=true, allowsingular=false) -> K::KLUFactorization
    klu!(K::KLUFactorization, nzval::Vector{Tv}; check=true, allowsingular=false) -> K::KLUFactorization

Recompute the KLU factorization `K` using the values of `A` or `nzval`. The pattern of the original
matrix used to create `K` must match the pattern of `A`. If `K` has not been factored yet, as after
`klu(A; full_factor = false)`, this computes its first numeric factorization.

If this throws because the new values are singular, `K` has no numeric factorization until a
later `klu!` or [`klu_factor!`](@ref) succeeds. Solving with `K` in the meantime factors the
singular values again, and so throws as well.

For sparse `A` with real or complex element type, the return type of `K` is
`KLUFactorization{Tv, Ti}`, with `Tv` = `Float64` or `ComplexF64`
respectively and `Ti` is an integer type (`Int32` or `Int64`).

See also: [`klu`](@ref)

# Arguments
  - `K::KLUFactorization`: The matrix factorization object, previously created by a call to `klu`, to be re-factored.
  - `A::SparseMatrixCSC` or `nzval::Vector{Tv}`: The sparse matrix or its nonzero values to be factored.
  - `check::Bool`: If `true` (default) check for errors after the factorization. If `false` errors must be checked by the user with `klu.common.status`.
  - `allowsingular::Bool`: If `true` (default `false`) allow the factorization to proceed even if the matrix is singular. Note that this will allow for
    silent divide by zero errors in subsequent `solve!` or `ldiv!` calls if singularity is not checked by the user with `klu.common.status == KLU.KLU_SINGULAR`

!!! note
    `klu(A::SparseMatrixCSC)` uses the KLU[^ACM907] library that is part of
    SuiteSparse. As this library only supports sparse matrices with `Float64` or
    `ComplexF64` elements, `klu!` converts other values to one of these, in a new vector.
    Otherwise `K` keeps the vector it is given, see [`klu`](@ref) for what this means.

[^ACM907]: Davis, Timothy A., & Palamadai Natarajan, E. (2010). Algorithm 907: KLU, A Direct Sparse Solver for Circuit Simulation Problems. ACM Trans. Math. Softw., 37(3). doi:10.1145/1824801.1824814
"""
klu!

for Tv ∈ KLUValueTypes, Ti ∈ KLUIndexTypes
    refactor = _klu_name("refactor", Tv, Ti)
    @eval begin
        function klu!(K::KLUFactorization{$Tv, $Ti}, nzval::Vector{$Tv}; check=true, allowsingular=false)
            length(nzval) != length(K.nzval)  && throw(DimensionMismatch())
            Base.@lock K begin
                _check_lengths(K, nzval)
                K.nzval = nzval
                K._numeric == C_NULL && return klu_factor!(K; check, allowsingular)
                K.common.halt_if_singular = !allowsingular && check
                ok = $refactor(K.colptr, K.rowval, K.nzval, K._symbolic, K._numeric, Ref(K.common))
                K.common.halt_if_singular = true
                if (ok == 1 || !check || (allowsingular && K.common.status >= KLU_OK))
                    return K
                else
                    # libklu stopped partway, leaving a mix of the old and new factors.
                    K._numeric = C_NULL
                    kluerror(K.common)
                end
            end
        end
    end
end

