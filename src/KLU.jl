    nonzeros(K::KLUFactorization) -> Vector

The values of the matrix factored by `K`.

!!! warning "nonzeros(K) may or may not point to nonzeros(A)"
    After `K = klu(A)`, `nonzeros(K) === nonzeros(A)` if `A` has `Float64` or `ComplexF64` values,
