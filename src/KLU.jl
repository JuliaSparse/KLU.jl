function kluerror(status::Integer)
    if status == KLU_OK
        return
    elseif status == KLU_SINGULAR
        throw(LinearAlgebra.SingularException(0))
    elseif status == KLU_OUT_OF_MEMORY
        throw(OutOfMemoryError())
    elseif status == KLU_INVALID
        throw(ArgumentError("libklu reported invalid input (KLU_INVALID), such as a malformed sparsity pattern or invalid settings in `common`."))
    elseif status == KLU_TOO_LARGE
        throw(OverflowError("libklu reported an integer overflow (KLU_TOO_LARGE). Try Int64 indices."))
    else
        throw(ErrorException("Unknown KLU error code: $status"))
    end
end

function kluerror(common::Union{klu_l_common, klu_common})
    # `singular_col` is the zero-based index of a column for which libklu found no pivot.
    common.status == KLU_SINGULAR && throw(LinearAlgebra.SingularException(common.singular_col + 1))
    return kluerror(common.status)
end

"""
Data structure for parameters of and statistics generated by KLU functions.

# Fields
- `tol::Float64`: Partial pivoting tolerance for diagonal preference
- `btf::Int64`: If `btf != 0` use BTF pre-ordering
- `ordering::Int64`: If `ordering == 0` use AMD to permute, if `ordering == 1` use COLAMD, \
if `ordering == 2` use the permutations given to [`klu_analyze!`](@ref), if `ordering == 3` use the user provided ordering function.
- `scale::Int64`: If `scale == 1` then `A[i,:] ./= sum(abs.(A[i,:]))`, if `scale == 2` then \
`A[i,:] ./= maximum(abs.(A[i,:]))`. If `scale == 0` no scaling is done, and the input is \
checked for errors if `scale >= 0`.

See the [KLU User Guide](https://github.com/DrTimothyAldenDavis/SuiteSparse/raw/dev/KLU/Doc/KLU_UserGuide.pdf)
for more information.
"""
klu_l_common

"""
Data structure for parameters of and statistics generated by KLU functions.

This is the `Int32` version of [`klu_l_common`](@ref).
"""
klu_common

function _klu_name(name, Tv, Ti)
    outname = "klu_" * (Tv === :Float64 ? "" : "z") * (Ti === :Int64 ? "l_" : "_") * name
    return Symbol(replace(outname, "__"=>"_"))
end
function _common(T)
    # SparseArrays requires this before any use of libklu. Otherwise its solvers switch the
    # allocator on first use, and memory from libc's malloc is then freed through `jl_free`.
    # Each KLUFactorization gets its `common` here, before libklu allocates anything for it.
    SparseArrays.LibSuiteSparse.init_suitesparse()
    if T == Int64
        common = klu_l_common()
        ok = klu_l_defaults(Ref(common))
    elseif T == Int32
        common = klu_common()
        ok = klu_defaults(Ref(common))
    else
        throw(ArgumentError("Index type must be Int64 or Int32"))
    end
    if ok == 1
        return common
    else
        throw(ErrorException("Could not initialize common struct."))
    end
end

abstract type AbstractKLUFactorization{Tv, Ti} <: LinearAlgebra.Factorization{Tv} end

# At exit Julia runs *all* finalizers, even for objects in use by tasks still running on other
# threads, so freeing factors then crashes in-flight solves. `atexit` hooks run before this
# finalizer pass, so use one to leave that memory to the OS.
const _EXITING = Threads.Atomic{Bool}(false)
function __init__()
    atexit(() -> (_EXITING[] = true; nothing))
    return
end


# libklu only sees pointers, so it would read past the end of vectors that are too short.
# It also rejects n <= 0 itself, but only with a generic KLU_INVALID.
function _check_lengths(n, colptr, rowval, nzval)
    n >= 1 || throw(ArgumentError("KLU cannot factor an empty matrix: n must be positive, but it is $n."))
    length(colptr) == n + 1 && colptr[end] <= min(length(rowval), length(nzval)) ||
        throw(ArgumentError("colptr must have length n + 1, and rowval and nzval at least colptr[end] entries."))
    return nothing
end

"""
    KLUFactorization <: Factorization

Matrix factorization type of the KLU factorization of a sparse matrix `A`.
This is the return type of [`klu`](@ref), the corresponding matrix factorization function.

The factors can be obtained from `K::KLUFactorization` via `K.L`, `K.U` and `K.F`
See the [`klu`](@ref) docs for more information.

You typically should not construct this directly, instead use [`klu`](@ref).

# Thread safety

Every operation on a `KLUFactorization` that calls into libklu (`solve!`, `ldiv!`, `\\`,
`klu!`, `klu_factor!`, `klu_analyze!`, `rcond`, `condest`, `rgrowth`, and access to the
factors `K.L`, `K.U`, `K.F`, ...) is serialized by a per-object `ReentrantLock`,
which can be acquired with `lock(K)`/`unlock(K)` or `Base.@lock K ...`.

This is required because the KLU C library stores scratch workspace *inside* the numeric
factorization object (`Numeric->Xwork`), which `klu_solve`, `klu_tsolve`, `klu_refactor`,
and `klu_condest` all use. Two concurrent calls on the same factorization would therefore
corrupt each other's results. Distinct `KLUFactorization` objects share no state and can be
used from different threads simultaneously without contention.
"""
mutable struct KLUFactorization{Tv<:KLUTypes, Ti<:KLUITypes} <: AbstractKLUFactorization{Tv, Ti}
    const common::Union{klu_l_common, klu_common}
    # Only these, `nzval` and `_perms` stay mutable, as they change when `K` is analyzed or factored.
    _symbolic::Ptr{Cvoid}
    _numeric::Ptr{Cvoid}
    const n::Int
    const colptr::Vector{Ti}
    const rowval::Vector{Ti}
    nzval::Vector{Tv}
    # Serializes all libklu calls on this object. KLU keeps per-call scratch space inside
    # the Numeric object, so concurrent solves/refactors on one factorization are a data race.
    const lock::ReentrantLock
    # The permutations given to `klu_analyze!`, if any, so that a copy can analyze with them.
    _perms::Union{Nothing, Tuple{Vector{Ti}, Vector{Ti}}}
    function KLUFactorization(n, colptr, rowval, nzval, common = _common(eltype(colptr)))
        _check_lengths(n, colptr, rowval, nzval)
        Ti = eltype(colptr)
        obj = new{eltype(nzval), Ti}(common, C_NULL, C_NULL, n, colptr, rowval, nzval, ReentrantLock(), nothing)
        # During normal operation an object being finalized is unreachable, so no other task
        # can be holding its lock or be inside a libklu call on it. (Any in-flight call keeps
        # the object rooted.) That does not hold at process exit, see `_EXITING`.
        function f(klu)
            _EXITING[] && return
            _free_symbolic(klu)
            _free_numeric(klu)
        end
        return finalizer(f, obj)
    end
end

# `K` shares its vectors with the caller, who could have resized them since they were checked.
_check_lengths(K::KLUFactorization, nzval = K.nzval) = _check_lengths(K.n, K.colptr, K.rowval, nzval)

"""
    lock(K::KLUFactorization)
    unlock(K::KLUFactorization)
    trylock(K::KLUFactorization)
    islocked(K::KLUFactorization)

Acquire/release the per-object lock that serializes libklu calls on `K`.
All exported operations take this lock themselves; it is reentrant, so users may also hold
it across a sequence of operations (e.g. a refactorization followed by several solves) to
make that sequence atomic with respect to other tasks.
"""
Base.lock(K::AbstractKLUFactorization) = lock(getfield(K, :lock))
Base.unlock(K::AbstractKLUFactorization) = unlock(getfield(K, :lock))
Base.trylock(K::AbstractKLUFactorization) = trylock(getfield(K, :lock))
Base.islocked(K::AbstractKLUFactorization) = islocked(getfield(K, :lock))

function _free_symbolic(K::AbstractKLUFactorization{Tv, Ti}) where {Ti<:KLUITypes, Tv}
    K._symbolic == C_NULL && return C_NULL
    if Ti == Int64
        klu_l_free_symbolic(Ref(Ptr{klu_l_symbolic}(K._symbolic)), Ref(K.common))
    elseif Ti == Int32
        klu_free_symbolic(Ref(Ptr{klu_symbolic}(K._symbolic)), Ref(K.common))
    end
    setfield!(K, :_symbolic, C_NULL)
end

for Ti ∈ KLUIndexTypes, Tv ∈ KLUValueTypes
    klufree = _klu_name("free_numeric", Tv, Ti)
    ptr = _klu_name("numeric", :Float64, Ti)
    @eval begin
        function _free_numeric(K::AbstractKLUFactorization{$Tv, $Ti})
            K._numeric == C_NULL && return C_NULL
            $klufree(Ref(Ptr{$ptr}(K._numeric)), Ref(K.common))
            setfield!(K, :_numeric, C_NULL)
        end
    end
end

function KLUFactorization(A::SparseMatrixCSC{Tv, Ti}) where {Tv<:KLUTypes, Ti<:KLUITypes}
    n = size(A, 1)
    n == size(A, 2) || throw(ArgumentError("KLU only accepts square matrices."))
    # Copying here to match UMFPACK
    # Seems overly defensive, it's probably rare that the user will modify A before the
    # numeric factorization is done.
    return KLUFactorization(n, decrement(A.colptr), decrement(A.rowval), copy(A.nzval))
end

size(K::AbstractKLUFactorization) = (K.n, K.n)
function size(K::AbstractKLUFactorization, dim::Integer)
    if dim < 1
        throw(ArgumentError("size: dimension $dim out of range"))
    elseif dim == 1 || dim == 2
        return Int(K.n)
    else
        return 1
    end
end

nnz(K::AbstractKLUFactorization) = Base.@lock K K.lnz + K.unz + K.nzoff
