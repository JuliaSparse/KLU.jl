"""
    solve!(klu::Union{KLUFactorization, AdjointFactorization{Tv, KLUFactorization}, TransposeFactorization{Tv, KLUFactorization}}, B::StridedVecOrMat) -> B

Solve the linear system `AX = B` or `A'X = B` using the matrix factorization `klu` and right-hand side `B`.

This function overwrites `B` with the solution `X`, for a new solution vector `X` use `klu \\ B`.

# Arguments
  - `klu::KLUFactorization`: The matrix factorization of `A` to use in the solution.
  - `B::StridedVecOrMat`: The right-hand side of the linear system. This may be a view such as `@view C[1:n, 2:4]`, \
  as long as each column is contiguous in memory and multiple columns are in increasing memory order. Other layouts throw an `ArgumentError`.
  - `check::Bool`: If `true` (default) check for errors after the solve. If `false` errors must be checked using `klu.common.status`. The return value of this function is always `B`, so the status of the solve *must* be checked using the factorization object itself when `check=false`.

!!! warning "Solve with a singular factorization object"
    If the factorization object `klu` has `klu.common.status == KLU.KLU_SINGULAR` then the `solve!` or `ldiv!` will result in a silent divide by zero error.

    This status should be checked by the user before solve calls if singularity checks were disabled on factorization using `check=false` or `allowsingular=true`.

!!! note "Thread safety"
    `solve!` holds the per-object lock of `klu` for the duration of the call (libklu uses
    workspace stored inside the factorization), so concurrent solves against one
    `KLUFactorization` are correct but serialized. Solves against different factorization
    objects proceed in parallel. Batch multiple right-hand sides into the columns of `B`
    to solve them in a single call.
"""
solve!
# libklu's solvers reset `common.status`, so the methods below restore it, or a solve would
# hide KLU_SINGULAR.
for Tv ∈ KLUValueTypes, Ti ∈ KLUIndexTypes
    solve_name = _klu_name("solve", Tv, Ti)
    @eval begin
        function solve!(klu::AbstractKLUFactorization{$Tv, $Ti}, B::StridedVecOrMat{$Tv}; check=true)
            ldim = _ldim(B)
            size(B, 1) == size(klu, 1) || throw(DimensionMismatch())
            Base.@lock klu begin
                klu._numeric == C_NULL && klu_factor!(klu; check)
                status = klu.common.status
                isok = $solve_name(klu._symbolic, klu._numeric, ldim, size(B, 2), B, Ref(klu.common))
                isok == 0 ? (check && kluerror(klu.common)) : (klu.common.status = status)
            end
            return B
        end
    end
end

for Tv ∈ KLUValueTypes, Ti ∈ KLUIndexTypes
    tsolve = _klu_name("tsolve", Tv, Ti)
    if Tv === :ComplexF64
        call = :($tsolve(klu._symbolic, klu._numeric, ldim, size(B, 2), B, conj, Ref(klu.common)))
    else
        call = :($tsolve(klu._symbolic, klu._numeric, ldim, size(B, 2), B, Ref(klu.common)))
    end
    @eval begin
        function solve!(klu::AdjointFactorization{$Tv, K}, B::StridedVecOrMat{$Tv}; check=true) where {K<:AbstractKLUFactorization{$Tv, $Ti}}
            conj = 1
            klu = parent(klu)
            ldim = _ldim(B)
            size(B, 1) == size(klu, 1) || throw(DimensionMismatch())
            Base.@lock klu begin
                klu._numeric == C_NULL && klu_factor!(klu; check)
                status = klu.common.status
                isok = $call
                isok == 0 ? (check && kluerror(klu.common)) : (klu.common.status = status)
            end
            return B
        end
        function solve!(klu::TransposeFactorization{$Tv, K}, B::StridedVecOrMat{$Tv}; check=true) where {K<: AbstractKLUFactorization{$Tv, $Ti}}
            conj = 0
            klu = parent(klu)
            ldim = _ldim(B)
            size(B, 1) == size(klu, 1) || throw(DimensionMismatch())
            Base.@lock klu begin
                klu._numeric == C_NULL && klu_factor!(klu; check)
                status = klu.common.status
                isok = $call
                isok == 0 ? (check && kluerror(klu.common)) : (klu.common.status = status)
            end
            return B
        end
    end
end

function solve(klu, B; check=true)
    X = copy(B)
    return solve!(klu, X; check)
end

